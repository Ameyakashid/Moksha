#!/usr/bin/env python3
"""Regenerate nine existing procedural sounds in a temporary directory only.

Same Python runtime repeatability check, not audible/mix quality or a claim that
all audio is procedurally generated by these two scripts. No asset is rewritten.
"""
from pathlib import Path
import hashlib
import json
import shutil
import subprocess
import sys
import tempfile

ROOT = Path(__file__).resolve().parents[2]
EXPECTED = {'ambience.wav', 'dash.wav', 'guard_draw.wav', 'hit.wav', 'hurt.wav',
            'jump.wav', 'prop.wav', 'swing.wav', 'win.wav'}

def main():
    results = []
    with tempfile.TemporaryDirectory(prefix='moksha-audio-repro-') as directory:
        target = Path(directory)
        for name in ('generate_audio.py', 'generate_guard_draw.py'):
            shutil.copyfile(ROOT/'audio'/name, target/name)
            subprocess.run([sys.executable, str(target/name)], check=True,
                           capture_output=True, text=True, timeout=30)
        generated = {path.name for path in target.glob('*.wav')}
        for name in sorted(EXPECTED | generated):
            source, rebuilt = ROOT/'audio'/name, target/name
            identical = source.is_file() and rebuilt.is_file() and source.read_bytes() == rebuilt.read_bytes()
            results.append({'path': 'audio/'+name, 'identical': identical,
                            'sha256': hashlib.sha256(rebuilt.read_bytes()).hexdigest() if rebuilt.exists() else None})
    report = {'passed': generated == EXPECTED and all(row['identical'] for row in results),
              'generated_set_matches': generated == EXPECTED, 'files': results,
              'python': sys.version, 'audio_listened': False,
              'scope': 'Nine WAVs regenerated in isolation. Existing tap.wav and step.wav are outside these generators.'}
    print(json.dumps(report, indent=2))
    return 0 if report['passed'] else 1

if __name__ == '__main__':
    raise SystemExit(main())
